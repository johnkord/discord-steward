    [Theory]
    [MemberData(nameof(OutputTypes))]
    public void OutputDto_DoesNotExposeCredentialsMessagesOrDiscordEntities(Type outputType)
    {
        var properties = outputType.GetProperties(BindingFlags.Instance | BindingFlags.Public);

        Assert.DoesNotContain(properties, property =>
            property.Name.Equals("Token", StringComparison.OrdinalIgnoreCase) ||
            property.Name.Equals("BotToken", StringComparison.OrdinalIgnoreCase) ||
            property.Name.Equals("MessageBody", StringComparison.OrdinalIgnoreCase) ||
            property.Name.Equals("MessageContent", StringComparison.OrdinalIgnoreCase));
        Assert.DoesNotContain(properties, property => ContainsDiscordNetType(property.PropertyType));
    }

    private static bool ContainsDiscordNetType(Type type)
    {
        if (type.Namespace?.StartsWith("Discord.", StringComparison.Ordinal) == true)
        {
            return true;
        }

        if (type.IsArray)
        {
            return ContainsDiscordNetType(type.GetElementType()!);
        }

        return type.IsGenericType && type.GetGenericArguments().Any(ContainsDiscordNetType);
    }
